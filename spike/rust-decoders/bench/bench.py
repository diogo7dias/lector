"""Pre-build step for the bench: patch the decoder checkouts as the firmware does, build the
Rust staticlib for this env's target, compile the firmware's own inflate wrappers, and embed
the test images (test/epubs, test/fuzz/image/corpus) as flash arrays in src/images.h."""

Import("env")  # noqa: F821
import os
import struct
import subprocess
import zipfile
import zlib

BENCH = env["PROJECT_DIR"]  # noqa: F821
CRATE = os.path.dirname(BENCH)
REPO = os.path.dirname(os.path.dirname(CRATE))
PIOENV = env["PIOENV"]  # noqa: F821


def patch(lib, folder):
    lib_dir = os.path.join(env.subst("$PROJECT_LIBDEPS_DIR"), PIOENV, lib)  # noqa: F821
    if not os.path.isdir(lib_dir):
        return
    pdir = os.path.join(REPO, "scripts", folder)
    for p in sorted(f for f in os.listdir(pdir) if f.endswith(".patch")):
        path = os.path.join(pdir, p)
        if subprocess.run(["git", "apply", "--check", "--reverse", path], cwd=lib_dir, capture_output=True).returncode == 0:
            continue
        subprocess.run(["git", "apply", path], cwd=lib_dir, check=True)
        print(f"bench: applied {folder}/{p}")


def rust():
    target = env.GetProjectOption("custom_rust_target")  # noqa: F821
    cmd = ["cargo", "build", "--release", "--target", target, "--manifest-path", os.path.join(CRATE, "Cargo.toml")]
    if target.startswith("xtensa"):
        cmd[1:1] = ["+esp"]
        cmd += ["-Zbuild-std=core,alloc"]
    subprocess.run(cmd, check=True)
    env.Append(LIBPATH=[os.path.join(CRATE, "target", target, "release")], LIBS=["lector_rdec"])  # noqa: F821


def firmware_sources():
    lib = os.path.join(REPO, "lib")
    deps = os.path.join(env.subst("$PROJECT_LIBDEPS_DIR"), PIOENV)  # noqa: F821
    env.Append(CPPPATH=[os.path.join(deps, d, "src") for d in ("JPEGDEC", "PNGdec")])  # noqa: F821
    env.Append(CPPPATH=[os.path.join(CRATE, "csrc")] + [os.path.join(lib, d) for d in ("miniz/src", "uzlib/src", "InflateReader", "Memory")])  # noqa: F821
    for name, src, flt in (
        ("fw_miniz", "miniz/src", "+<miniz_impl.c> +<InflateStream.cpp>"),
        ("fw_uzlib", "uzlib/src", "+<tinflate.c>"),
        ("fw_inflatereader", "InflateReader", "+<*.cpp>"),
    ):
        env.BuildSources(os.path.join("$BUILD_DIR", name), os.path.join(lib, src), flt)  # noqa: F821
    env.BuildSources(os.path.join("$BUILD_DIR", "csrc"), os.path.join(CRATE, "csrc"), "+<*.cpp>")  # noqa: F821


def raw_entries(epub):
    """The deflated members of an EPUB as stored: raw deflate, exactly what ZipFile inflates."""
    data = open(epub, "rb").read()
    out = []
    with zipfile.ZipFile(epub) as z:
        for i in z.infolist():
            if i.compress_type != zipfile.ZIP_DEFLATED:
                continue
            off = i.header_offset
            n, m = struct.unpack("<HH", data[off + 26 : off + 30])
            start = off + 30 + n + m
            out.append((os.path.basename(epub) + ":" + i.filename, data[start : start + i.compress_size]))
    return out


def images():
    cases, seen = [], set()
    for epub in ("test_jpeg_images.epub", "test_inline_images.epub"):
        path = os.path.join(REPO, "test", "epubs", epub)
        with zipfile.ZipFile(path) as z:
            for n in z.namelist():
                if n.endswith((".jpg", ".png")):
                    cases.append((n.split("/")[-1], "J" if n.endswith(".jpg") else "P", z.read(n)))
        cases += [(name, "D", raw) for name, raw in raw_entries(path)]
    corpus = os.path.join(REPO, "test", "fuzz", "image", "corpus")
    for f in sorted(os.listdir(corpus)):
        if not f.startswith("seed_"):
            continue
        payload = open(os.path.join(corpus, f), "rb").read()[8:]
        if payload in seen:  # many seeds share one image and differ only in harness bytes
            continue
        seen.add(payload)
        cases.append((f[:-4], "P" if payload[:1] == b"\x89" else "J", payload))
    # A chapter-sized text stream: the user guide, deflated the way zip tools store it.
    text = open(os.path.join(REPO, "USER_GUIDE.md"), "rb").read()
    c = zlib.compressobj(6, zlib.DEFLATED, -15)
    cases.append(("USER_GUIDE.md(deflate -6)", "D", c.compress(text) + c.flush()))
    return cases


def write_header(cases):
    lines = ["// Generated by bench.py; not committed.", "#pragma once", "#include <stdint.h>", ""]
    for i, (_, _, data) in enumerate(cases):
        body = ",".join(str(b) for b in data)
        lines.append(f"static const uint8_t kImg{i}[] = {{{body}}};")
    lines.append("struct BenchCase { const char* name; char kind; const uint8_t* data; uint32_t len; };")
    lines.append("static const BenchCase kCases[] = {")
    lines += [f'  {{"{name}", \'{kind}\', kImg{i}, {len(data)}}},' for i, (name, kind, data) in enumerate(cases)]
    lines.append("};")
    path = os.path.join(BENCH, "src", "images.h")
    text = "\n".join(lines) + "\n"
    if not os.path.exists(path) or open(path).read() != text:
        open(path, "w").write(text)


patch("JPEGDEC", "jpegdec_patches")
patch("PNGdec", "pngdec_patches")
rust()
firmware_sources()
write_header(images())
