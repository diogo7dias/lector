TEST(FirmwareSignature, AcceptsTheSignersOutput) { EXPECT_TRUE(firmware_signature::verify(TEST_KEY, DIGEST, SIG)); }

TEST(FirmwareSignature, RejectsAnotherImage) {
  uint8_t digest[32];
  std::memcpy(digest, DIGEST, sizeof(digest));
  digest[31] ^= 1;
  EXPECT_FALSE(firmware_signature::verify(TEST_KEY, digest, SIG));
}

TEST(FirmwareSignature, RejectsATamperedSignature) {
  uint8_t sig[firmware_signature::SIG_SIZE];
  std::memcpy(sig, SIG, sizeof(sig));
  sig[40] ^= 0x80;
  EXPECT_FALSE(firmware_signature::verify(TEST_KEY, DIGEST, sig));
}

TEST(FirmwareSignature, ReleaseKeyDoesNotAcceptTheTestKeysSignature) {
  EXPECT_FALSE(firmware_signature::verifyRelease(DIGEST, SIG));
}

